export interface TaleCover {
  /** 480px wide WebP. */
  small: string
  /** 960px wide WebP. */
  large: string
  width: number
  height: number
  alt: string
}

export interface ShelfTale {
  id: ShowcaseTaleId
  name: string
  tag: string
  cover: TaleCover
}

function cover(
  id: ShowcaseTaleId,
  width: number,
  height: number,
  alt: string
): TaleCover {
  return {
    small: `/prikazki/covers/${id}-480.webp`,
    large: `/prikazki/covers/${id}-960.webp`,
    width,
    height,
    alt
  }
}

