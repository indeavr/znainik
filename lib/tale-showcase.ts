/**
 * Which of the four tales a Notion series („Епизоди“) belongs to, so its
 * episode pages are linked from the right section. Unknown series → null.
 */
export function matchShowcaseTale(tale: {
  slug: string
  title: string
}): ShowcaseTaleId | null {
  const text = `${tale.slug} ${tale.title}`.toLocaleLowerCase('bg')

  if (/творе|tvorey|raz.?tvori|раз.?твори/u.test(text)) return 'tvoreya'
  if (/амбри|ambri/u.test(text)) return 'ambria'
  if (/(^|[^\p{L}])(фи|fi)([^\p{L}]|$)/u.test(text)) return 'fi'
  if (/азайр|azair/u.test(text)) return 'azaira'
  return null
}
